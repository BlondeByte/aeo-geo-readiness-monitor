import os
from pathlib import Path
import streamlit as st
import pandas as pd

# ---------------------------------------------------------------------------
# Page Configuration
# ---------------------------------------------------------------------------
st.set_page_config(
    page_title="AEO/GEO Readiness Auditor",
    page_icon="⚡",
    layout="wide",
    initial_sidebar_state="expanded",
)

# ---------------------------------------------------------------------------
# File & Data Loading
# ---------------------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parent
RESULTS_CSV = BASE_DIR / "aeo_audit_results.csv"


@st.cache_data(ttl=60)
def load_audit_data(file_path: Path) -> pd.DataFrame | None:
    """Load and cache the audit results generated by analyzer.py."""
    if not file_path.exists():
        return None
    try:
        df = pd.read_csv(file_path)
        return df
    except Exception as err:
        st.error(f"Error loading {file_path.name}: {err}")
        return None


# ---------------------------------------------------------------------------
# Header & KPI Metric Cards
# ---------------------------------------------------------------------------
st.title("⚡ AEO & GEO Answer Readiness Auditor")
st.markdown(
    "Auditing page-level information architecture, JSON-LD schema grounding, "
    "direct-answer syntax, and authority citation signals for Generative Search Engines."
)

data = load_audit_data(RESULTS_CSV)

if data is None or data.empty:
    st.warning(
        f"No audit records found at `{RESULTS_CSV.name}`. Run `python analyzer.py` to generate audit data."
    )
    st.stop()

# Compute summary aggregate metrics
total_audited = len(data)
avg_score = float(data["total_score"].mean())
schema_adoption = float((data["has_schema"].sum() / total_audited) * 100)
tier1_count = int((data["total_score"] >= 90).sum())

col1, col2, col3, col4 = st.columns(4)
with col1:
    st.metric(label="Pages Audited", value=total_audited)
with col2:
    st.metric(
        label="Mean AEO Score",
        value=f"{avg_score:.1f} / 100",
        delta=f"{avg_score - 75:.1f} vs Target (75)",
    )
with col3:
    st.metric(label="Schema Adoption", value=f"{schema_adoption:.0f}%")
with col4:
    st.metric(label="Tier 1 Readiness", value=f"{tier1_count} / {total_audited}")

st.divider()

# ---------------------------------------------------------------------------
# Section 1: Ranked Audit Overview & Distribution Chart
# ---------------------------------------------------------------------------
st.subheader("📊 Ranked URL Performance")

display_cols = [
    "url",
    "total_score",
    "readiness_tier",
    "score_hierarchy",
    "score_schema",
    "score_scannability",
    "score_authority",
]

col_left, col_right = st.columns([3, 2])

with col_left:
    st.dataframe(
        data[display_cols].rename(
            columns={
                "url": "URL",
                "total_score": "Total Score",
                "readiness_tier": "Readiness Tier",
                "score_hierarchy": "Hierarchy (25)",
                "score_schema": "Schema (25)",
                "score_scannability": "Scannability (30)",
                "score_authority": "Authority (20)",
            }
        ),
        use_container_width=True,
        hide_index=True,
    )

with col_right:
    chart_data = data[["url", "total_score"]].set_index("url")
    st.bar_chart(chart_data)

st.divider()

# ---------------------------------------------------------------------------
# Section 2: Deep-Dive Single Page Inspector
# ---------------------------------------------------------------------------
st.subheader("🔍 Deep-Dive Page Inspector")

selected_url = st.selectbox(
    "Select a page to inspect granular dimensional scores and extraction signals:",
    options=data["url"].tolist(),
)

if selected_url:
    row = data[data["url"] == selected_url].iloc[0]

    st.markdown(f"**Target URL:** `{row['url']}`")
    st.markdown(f"**Tier Classification:** `{row['readiness_tier']}`")

    # Granular Score Breakdown
    d1, d2, d3, d4 = st.columns(4)
    with d1:
        st.metric(label="Hierarchy Score", value=f"{row['score_hierarchy']} / 25")
    with d2:
        st.metric(label="Schema Score", value=f"{row['score_schema']} / 25")
    with d3:
        st.metric(label="Scannability Score", value=f"{row['score_scannability']} / 30")
    with d4:
        st.metric(label="Authority Score", value=f"{row['score_authority']} / 20")

    # On-Page Signal Diagnostics
    st.markdown("#### Structural Signals Detected")
    sig_col1, sig_col2, sig_col3, sig_col4 = st.columns(4)

    with sig_col1:
        st.write(f"• **H1 Count:** `{row['h1_count']}`")
        st.write(f"• **H2 Count:** `{row['h2_count']}`")

    with sig_col2:
        st.write(f"• **JSON-LD Schema:** `{'Yes' if row['has_schema'] else 'No'}`")
        st.write(f"• **Matched Schemas:** `{row['matched_schemas']}`")

    with sig_col3:
        st.write(f"• **Has Tables:** `{'Yes' if row['has_tables'] else 'No'}`")
        st.write(f"• **Has Lists:** `{'Yes' if row['has_lists'] else 'No'}`")

    with sig_col4:
        st.write(f"• **External Citations:** `{row['external_links']}`")
